import { defineSchema, defineTable } from "convex/server";
import { v } from "convex/values";

export default defineSchema({
  internships: defineTable({
    title: v.string(),
    company: v.string(),
    category: v.string(),
    location: v.string(),
    work_mode: v.string(),
    duration: v.number(),
    stipend: v.optional(v.union(v.number(), v.null())),
    skills: v.any(),
    description: v.optional(v.string()),
    deadline: v.optional(v.union(v.string(), v.null())),
    status: v.string(),
    created_at: v.optional(v.string()),
  }),

  users: defineTable({
    name: v.string(),
    email: v.string(),
    phone: v.optional(v.string()),
    college: v.optional(v.string()),
    domain: v.optional(v.string()),
    role: v.string(),
    created_at: v.optional(v.string()),
  }).index("by_email", ["email"]),

  applications: defineTable({
    internship_id: v.optional(v.number()),
    full_name: v.string(),
    email: v.string(),
    phone: v.string(),
    college: v.optional(v.string()),
    resume_url: v.string(),
    portfolio_url: v.optional(v.string()),
    skills_tags: v.optional(v.any()),
    cover_letter: v.optional(v.string()),
    consent_given: v.optional(v.number()),
    consent_ip: v.optional(v.string()),
    status: v.string(),
    created_at: v.optional(v.string()),
  }).index("by_email", ["email"]),

  offers: defineTable({
    offer_id: v.string(),
    application_id: v.optional(v.number()),
    user_id: v.optional(v.number()),
    intern_name: v.string(),
    track: v.string(),
    batch: v.optional(v.string()),
    duration: v.optional(v.string()),
    start_date: v.string(),
    end_date: v.string(),
    stipend_amount: v.number(),
    mentor_name: v.optional(v.string()),
    signatory_name: v.optional(v.string()),
    status: v.string(),
    expires_at: v.optional(v.string()),
    issued_at: v.optional(v.string()),
    accepted_at: v.optional(v.union(v.string(), v.null())),
  }).index("by_offer_id", ["offer_id"]),

  linkedin_proofs: defineTable({
    user_id: v.optional(v.number()),
    proof_type: v.string(),
    post_url: v.string(),
    screenshot_url: v.string(),
    status: v.string(),
    review_notes: v.optional(v.string()),
    submitted_at: v.optional(v.string()),
    reviewed_at: v.optional(v.union(v.string(), v.null())),
  }),

  screening_quizzes: defineTable({
    track: v.string(),
    title: v.string(),
    time_limit_mins: v.number(),
    pass_cutoff: v.number(),
    questions: v.string(),
  }),

  quiz_submissions: defineTable({
    user_id: v.optional(v.number()),
    quiz_id: v.optional(v.number()),
    score: v.number(),
    passed: v.number(),
    tab_switches: v.number(),
    copy_paste_log: v.optional(v.string()),
    submitted_at: v.optional(v.string()),
  }),

  tasks: defineTable({
    task_num: v.number(),
    title: v.string(),
    objective: v.string(),
    deliverable: v.string(),
    deadline_days: v.optional(v.number()),
    guide_url: v.optional(v.string()),
  }),

  task_submissions: defineTable({
    user_id: v.optional(v.number()),
    task_id: v.optional(v.number()),
    submission_url: v.string(),
    notes: v.optional(v.string()),
    is_late: v.optional(v.number()),
    plagiarism_flag: v.optional(v.number()),
    status: v.string(),
    feedback: v.optional(v.string()),
    rubric_score: v.optional(v.number()),
    submitted_at: v.optional(v.string()),
    reviewed_at: v.optional(v.union(v.string(), v.null())),
  }),

  weekly_reports: defineTable({
    user_id: v.optional(v.number()),
    week_number: v.number(),
    done_summary: v.string(),
    blockers: v.optional(v.string()),
    next_week: v.string(),
    submitted_at: v.optional(v.string()),
  }),

  final_projects: defineTable({
    user_id: v.optional(v.number()),
    project_title: v.string(),
    repo_url: v.string(),
    live_url: v.optional(v.string()),
    report_pdf_url: v.string(),
    self_assessment: v.string(),
    feedback_rating: v.number(),
    feedback_text: v.optional(v.string()),
    status: v.string(),
    submitted_at: v.optional(v.string()),
  }),

  certificates: defineTable({
    certificate_id: v.string(),
    user_id: v.optional(v.number()),
    intern_name: v.string(),
    college: v.string(),
    domain: v.string(),
    internship_title: v.string(),
    company: v.string(),
    start_date: v.string(),
    completion_date: v.string(),
    grade: v.string(),
    lor_text: v.optional(v.string()),
    status: v.string(),
    issued_at: v.optional(v.string()),
  }).index("by_certificate_id", ["certificate_id"]),

  in_app_notifications: defineTable({
    user_id: v.optional(v.number()),
    title: v.string(),
    message: v.string(),
    is_read: v.number(),
    created_at: v.optional(v.string()),
  }),

  audit_logs: defineTable({
    action: v.string(),
    actor: v.string(),
    details: v.string(),
    timestamp: v.optional(v.string()),
  }),
});
